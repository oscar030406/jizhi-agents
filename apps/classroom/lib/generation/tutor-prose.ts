/**
 * 导学口语的渲染前清理。
 *
 * ## 为什么要这一层
 *
 * 2026-08-13 以零基础视角实测，导学面板里蹦出这一句：
 *
 * > 「参考 **[tu04#s2]** 读到 query 函数时，注意看它怎么把问题向量和所有文档向量做比对。」
 *
 * `tu04#s2` 是知识库的 source_id。它在讲义里有意义（角标可下钻到原文），
 * 但在导学的**口语**里没有：结构化引用走的是 `explanation.source_ids` 字段
 * （实测那一轮是空数组），这个方括号只是模型把讲义里的标记抄进了对话。
 * 一个没写过代码的学习者看到它，只会以为自己漏了什么。
 *
 * 这里只做删除，不做转链接：导学是对话，塞一个可点的角标会打断语流；
 * 真要溯源，讲义正文里那一份角标就在旁边。
 *
 * 纯函数、无 IO。根治要在导学 prompt 上禁写标记，那是模型侧的事，
 * 这一层是拿不到的那一侧的护栏——两者都要有。
 */

/**
 * 知识库 source_id 的形态：`tu04#s2` / `ha08s03#s1` / `pg10#s1`。
 * 收方括号包裹与裸写两种，前后允许「参考 / 见 / 详见」这类引导词一起吃掉，
 * 否则删完会留下「参考 ，注意看」这样的断句。
 */
const CITE_TOKEN = /(?:参考|详见|见|依据|出自)?\s*[［[]?\b[a-z]{2,6}\d{0,4}(?:s\d+)?#s\d+\b[］\]]?\s*[，,、]?/gi;

/** 删标记后常见的三种破碎标点，收干净。 */
const DANGLING = [
  [/\s*，\s*，/g, '，'],
  [/[（(]\s*[）)]/g, ''],
  [/^\s*[，,、。]\s*/gm, ''],
] as const;

/**
 * 从导学口语里去掉知识库 source_id。找不到就原样返回（不做任何其他改写）。
 */
export function stripSourceIds(text: string): string {
  if (!text || !text.includes('#s')) return text;
  let out = text.replace(CITE_TOKEN, '');
  for (const [re, to] of DANGLING) out = out.replace(re, to);
  return out.replace(/[ \t]{2,}/g, ' ').trim();
}
